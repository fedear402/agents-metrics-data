"""Check that the default render keeps hand-edited prose, and verify the cross-model test."""
from pathlib import Path
import json
import re
import importlib.util
import shutil

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
BASE = ROOT / 'data/production/main/manuscript_baseline'
PAPER = ROOT / 'paper/manuscript'


def test_default_render_keeps_hand_edited_prose(tmp_path):
    spec = importlib.util.spec_from_file_location('paper_manuscript_under_test', ROOT / 'code/paper/manuscript.py')
    renderer = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(renderer)
    paper = tmp_path / 'manuscript'
    for folder in ('sections', 'appendix', 'tables', 'figures'):
        shutil.copytree(PAPER / folder, paper / folder)
    for name in ('numbers.tex', 'numbers_pending.tex'):
        shutil.copyfile(PAPER / name, paper / name)
    base = tmp_path / 'baseline'
    shutil.copytree(BASE, base)
    renderer.MANUSCRIPT, renderer.BASE = paper, base
    renderer.REPORT = tmp_path / 'manuscript_changes.md'
    real = {p: p.read_bytes() for p in [PAPER / 'numbers.tex', BASE / 'latest_render.json']}
    before = {p: p.read_bytes() for folder in ('sections', 'appendix') for p in (paper / folder).glob('*.tex')}
    # render() also writes data/cross_model.json into the analysis folder; keep the canonical bytes.
    cross = ROOT / 'data/analysis/main/data/cross_model.json'
    saved = cross.read_bytes()
    try:
        renderer.render(ROOT / 'data/analysis/main')
    finally:
        cross.write_bytes(saved)
    assert {p: p.read_bytes() for p in before} == before
    assert {p: p.read_bytes() for p in real} == real
    assert (paper / 'numbers.tex').read_text().startswith('% Generated by code/paper/manuscript.py')


def test_every_prose_macro_is_defined():
    used = set()
    for folder in ('sections', 'appendix', 'tables'):
        for path in (PAPER / folder).glob('*.tex'):
            used |= set(re.findall(r'\\(num[A-Za-z]+)', path.read_text()))
    defined = set(re.findall(r'\\(?:newcommand|providecommand)\{\\(num[A-Za-z]+)\}', (PAPER / 'numbers.tex').read_text()))
    assert used <= defined, sorted(used - defined)


def test_cross_model_interaction_agrees_with_balanced_task_differences():
    folder = ROOT / 'data/analysis/main/data'
    runs = pd.read_csv(folder / 'runs.csv')
    result = json.loads((folder / 'cross_model.json').read_text())
    cells = runs.groupby(['task', 'model', 'agency', 'prompt']).primary.mean().unstack('prompt')
    gains = (cells.few_shot - cells.zero_shot).unstack('agency')
    interactions = (gains.agent - gains.chatbot).unstack('model')
    differences = interactions.sonnet - interactions.luna
    expected_se = differences.std(ddof=1) / np.sqrt(len(differences))
    expected_se *= np.sqrt((len(runs) - 1) / (len(runs) - result['n_params']))
    actual = result['differences']['H4_tool_loop']['sonnet_minus_luna']
    assert result['df'] == len(differences) - 1 == 39
    assert np.isclose(actual['estimate'], differences.mean(), atol=1e-12)
    assert np.isclose(actual['se_cr1'], expected_se, atol=1e-12)
