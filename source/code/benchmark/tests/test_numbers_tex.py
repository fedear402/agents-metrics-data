"""Guard tests for the generated manuscript macro file ``numbers.tex``.

Two guards:

1. The installed ``paper/manuscript/numbers.tex`` must match a fresh
   rendering by ``code/paper/manuscript.py`` from the canonical analysis
   ``data/analysis/main`` byte for byte, so stale numbers fail the suite
   after any analysis refresh. The rendering writes into a temporary folder.
2. The remaining tests check the historical builder ``build_numbers_tex.py``
   against the August analysis JSON files, independently of the builder's
   own helpers. The current manuscript does not use that builder.

The Overleaf-synced manuscript is a nested repo excluded from this one by
design; a fresh clone lacks it. The install-match test skips cleanly there.
"""

from __future__ import annotations

import importlib.util
import json
import re
import shutil
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

import pytest

BENCHMARK_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BENCHMARK_ROOT))

import build_numbers_tex as bnt  # noqa: E402

PROJECT_ROOT = BENCHMARK_ROOT.parents[1]
MANUSCRIPT = PROJECT_ROOT / "paper" / "manuscript"
CURRENT_ANALYSIS = PROJECT_ROOT / "data" / "analysis" / "main"
RENDER_BASELINE = PROJECT_ROOT / "data" / "production" / "main" / "manuscript_baseline"

requires_manuscript = pytest.mark.skipif(
    not MANUSCRIPT.exists(),
    reason="paper/manuscript is not present in this checkout",
)

# The value pattern tolerates one nested brace level, e.g. 9{,}999.
MACRO_RE = re.compile(
    r"\\newcommand\{\\(?P<name>[A-Za-z]+)\}"
    r"\{(?P<value>[^{}]*(?:\{[^{}]*\}[^{}]*)*)\}"
)
WEIGHT_RE = re.compile(r"%TC:macroword \\(?P<name>[A-Za-z]+) (?P<weight>\d+)")


def parse_macros(content: str) -> dict[str, str]:
    return {m.group("name"): m.group("value") for m in MACRO_RE.finditer(content)}


@pytest.fixture(scope="module")
def rendered() -> str:
    return bnt.render_numbers_tex()


@pytest.fixture(scope="module")
def analysis() -> dict:
    data_dir = PROJECT_ROOT / "data" / "analysis"
    return {
        "mn": json.loads((data_dir / "manuscript_numbers.json").read_text()),
        "fa": json.loads((data_dir / "full_analysis.json").read_text()),
        "fbm": json.loads((data_dir / "factorial_by_model.json").read_text()),
    }


@requires_manuscript
def test_installed_numbers_tex_is_current(tmp_path: Path) -> None:
    """Render the current analysis into a temporary copy and compare bytes."""
    spec = importlib.util.spec_from_file_location(
        "paper_manuscript_numbers_check", PROJECT_ROOT / "code" / "paper" / "manuscript.py"
    )
    renderer = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(renderer)
    paper = tmp_path / "manuscript"
    # The renderer reads the current hand-edited prose to find every macro in use.
    for folder in ("sections", "appendix"):
        shutil.copytree(MANUSCRIPT / folder, paper / folder)
    (paper / "figures").mkdir()
    base = tmp_path / "baseline"
    shutil.copytree(RENDER_BASELINE, base)
    renderer.MANUSCRIPT, renderer.BASE = paper, base
    renderer.REPORT = tmp_path / "manuscript_changes.md"
    renderer.render(CURRENT_ANALYSIS)

    rendered = (paper / "numbers.tex").read_bytes()
    assert rendered.startswith(b"% Generated by code/paper/manuscript.py.")
    installed = (MANUSCRIPT / "numbers.tex").read_bytes()
    assert installed == rendered, (
        "paper/manuscript/numbers.tex is stale; regenerate it with "
        "'uv run --no-sync python code/paper/manuscript.py --analysis data/analysis/main'"
    )


def _pct(successes: int, n: int) -> str:
    value = Decimal(successes) * 100 / Decimal(n)
    return str(value.quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


def test_spot_checked_macros_match_the_analysis_json(
    rendered: str, analysis: dict
) -> None:
    macros = parse_macros(rendered)
    fa, mn, fbm = analysis["fa"], analysis["mn"], analysis["fbm"]

    headline = fa["headline"]

    def pooled(model: str, axis: str, key: str) -> str:
        s = sum(headline[model][p][axis][key]["successes"] for p in ("zero_shot", "few_shot"))
        n = sum(headline[model][p][axis][key]["n"] for p in ("zero_shot", "few_shot"))
        return _pct(s, n)

    # 1. Overall Sonnet task success.
    s = sum(headline["sonnet"][p]["overall"]["successes"] for p in ("zero_shot", "few_shot"))
    n = sum(headline["sonnet"][p]["overall"]["n"] for p in ("zero_shot", "few_shot"))
    assert macros["numSonnetOverall"] == _pct(s, n)

    # 2. Pooled success over the two paper arms.
    st = sum(
        headline[m][p]["overall"]["successes"]
        for m in ("sonnet", "codex")
        for p in ("zero_shot", "few_shot")
    )
    nt = sum(
        headline[m][p]["overall"]["n"]
        for m in ("sonnet", "codex")
        for p in ("zero_shot", "few_shot")
    )
    assert macros["numPooledSuccess"] == _pct(st, nt)
    # The pooled macro must agree with the snapshot's own paper-scope block.
    paper = fa["paper_scope"]["pooled"]["overall"]
    assert macros["numPooledSuccess"] == _pct(paper["successes"], paper["n"])

    # 3. Sonnet constrained-agent rate, prompts pooled.
    assert macros["numSonnetAgent"] == pooled("sonnet", "by_interface", "constrained agent")

    # 4. Codex chatbot rate, prompts pooled.
    assert macros["numCodexChatbot"] == pooled("codex", "by_interface", "chatbot")

    # 5. Sonnet H3b contrast, magnitude in percentage points.
    est = Decimal(repr(fbm["sonnet"]["contrasts"]["H3_tool_loop"]["estimate"]))
    expected = str((abs(est) * 100).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))
    assert macros["numHThreeBAgentSonnet"] == expected

    # 6. Sonnet H2 wild-bootstrap p-value at three decimals.
    p = Decimal(repr(fbm["sonnet"]["contrasts"]["H2_fewshot"]["p_wcb"]))
    assert macros["numHTwoSonnetP"] == str(
        p.quantize(Decimal("0.001"), rounding=ROUND_HALF_UP)
    )

    # 7. Sonnet incremental cost per additional success, stored 2dp string.
    conv = mn["cost"]["sonnet_native"]["pooled_prompts"][
        "conversion_price_chatbot_to_constrained_agent"
    ]
    assert macros["numSonnetIncrementalCps"] == conv["usd_per_additional_success_2dp"]

    # 8. Sonnet constrained-agent median runtime.
    runtime = mn["runtime"]["by_model"]["sonnet"]["by_interface"]["constrained agent"]
    assert macros["numRuntimeAgentMedianSonnet"] == str(
        Decimal(repr(runtime["median_provider_wall_seconds"])).quantize(
            Decimal("0.1"), rounding=ROUND_HALF_UP
        )
    )

    # 9. Runs per arm, comma-grouped.
    n_arm = sum(headline["codex"][p]["overall"]["n"] for p in ("zero_shot", "few_shot"))
    assert macros["numRunsPerArm"] == f"{n_arm:,d}"

    # 10. Two-model pooled H3b contrast and its CR1 standard error.
    pooled_h3b = fbm["pooled"]["contrasts"]["H3_tool_loop"]
    for field, suffix in (("estimate", ""), ("se_cr1", "SE")):
        value = Decimal(repr(pooled_h3b[field]))
        assert macros[f"numHThreeBAgentPooled{suffix}"] == str(
            (abs(value) * 100).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)
        )
    # The pooled contrast is the mean of the two per-arm contrasts.
    arms_mean = sum(
        Decimal(repr(fbm[m]["contrasts"]["H3_tool_loop"]["estimate"]))
        for m in ("sonnet", "codex")
    ) / Decimal(2)
    assert abs(arms_mean - Decimal(repr(pooled_h3b["estimate"]))) < Decimal("1e-9")

    # 11. No macro names the dropped model arm.
    assert not [name for name in macros if "Deepseek" in name]

    # 12. One reported interaction, named H4 (decision record
    # 2026-08-24_h4-single-interaction).
    h4 = Decimal(repr(fbm["sonnet"]["contrasts"]["H4_tool_loop"]["estimate"]))
    assert macros["numHFourSonnet"] == str(
        (abs(h4) * 100).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)
    )
    h4_p = Decimal(repr(fbm["sonnet"]["contrasts"]["H4_tool_loop"]["p_wcb"]))
    assert macros["numHFourSonnetP"] == str(
        h4_p.quantize(Decimal("0.001"), rounding=ROUND_HALF_UP)
    )
    # 13. pass@1 on the twelve-repetition sample equals the observed rate.
    passk = mn["pass_at_k_paper"]["by_model"]["sonnet"]
    assert macros["numPassOneSonnet"] == _pct(s, n)
    assert macros["numPassTwelveSonnet"] == str(
        Decimal(repr(passk["overall"]["pass_at_k_pct"]["12"])).quantize(
            Decimal("0.1"), rounding=ROUND_HALF_UP
        )
    )

    # 14. Sonnet loud failures per 100 chatbot runs, using the cascade's own
    # stored n as the denominator (regression guard: the builder once
    # hard-coded the eight-rep cell size 504 here).
    loud = n_runs = 0
    for prompt in ("zero_shot", "few_shot"):
        cell = fa["extended"]["criterion_cascade"]["models"]["sonnet"][prompt]["chatbot"]
        loud += cell["counts"]["execution"] + cell["counts"]["artifact"]
        n_runs += cell["n"]
    assert macros["numLoudChatbotSonnet"] == _pct(loud, n_runs)


def test_the_reported_interaction_set_is_h4_alone(
    rendered: str, analysis: dict
) -> None:
    """The self-repair interaction and the joint test carry no macro."""
    macros = parse_macros(rendered)
    retired = [
        name
        for name in macros
        if name.startswith(("numHFourARepair", "numHFourBAgent", "numJointHFour",
                            "numHFourADiff", "numHFourBDiff"))
    ]
    assert not retired, retired
    assert any(name.startswith("numHFourDiff") for name in macros)
    # The estimate and its CR1 standard error always carry a macro. The
    # bootstrap p-value carries one only when it rounds above 0.000; below
    # that the builder omits it and the prose prints $p<0.001$ directly.
    estimation_keys = {"Sonnet": "sonnet", "Codex": "codex", "Pooled": "pooled"}
    for arm, estimation_key in estimation_keys.items():
        for suffix in ("", "SE"):
            assert f"numHFour{arm}{suffix}" in macros
        p_value = bnt.fmt_p(
            analysis["fbm"][estimation_key]["contrasts"]["H4_tool_loop"]["p_wcb"]
        )
        assert (f"numHFour{arm}P" in macros) == (p_value != "0.000"), arm


def test_every_macro_has_a_texcount_weight_matching_its_commas(rendered: str) -> None:
    macros = parse_macros(rendered)
    weights = {m.group("name"): int(m.group("weight")) for m in WEIGHT_RE.finditer(rendered)}
    assert set(weights) == set(macros)
    for name, value in macros.items():
        assert weights[name] == 1 + value.count(","), name


def test_macro_names_are_letters_only_and_unique(rendered: str) -> None:
    names = [m.group("name") for m in MACRO_RE.finditer(rendered)]
    assert len(names) == len(set(names))
    for name in names:
        assert re.fullmatch(r"[A-Za-z]+", name), name
        assert name.startswith("num"), name


